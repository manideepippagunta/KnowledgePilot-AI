"""Ollama local language model generator provider."""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from collections.abc import Iterator
from typing import Any

from knowledgepilot.generation.base import BaseGenerator
from knowledgepilot.generation.errors import GenerationError


class OllamaGenerator(BaseGenerator):
    """Local LLM provider adapter communicating with Ollama via HTTP REST API.

    Requires an active Ollama instance (typically running at http://localhost:11434).
    Zero third-party dependencies required; communicates via standard library HTTP.
    """

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        model: str = "llama3.2:3b",
        timeout: float = 30.0,
    ) -> None:
        """Initialize the Ollama generator.

        Args:
            base_url: HTTP endpoint of the local Ollama daemon.
            model: Name of the pulled Ollama model (e.g. 'llama3.2:3b', 'phi3').
            timeout: Request timeout in seconds.
        """
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.timeout = timeout

    def is_available(self) -> bool:
        """Check whether the local Ollama service is reachable.

        Returns:
            True if Ollama is running and responds with HTTP 200; False otherwise.
        """
        url = f"{self.base_url}/api/tags"
        req = urllib.request.Request(url, method="GET")
        try:
            with urllib.request.urlopen(req, timeout=2.0) as response:
                status = getattr(response, "status", 200)
                return bool(status == 200)
        except Exception:
            return False

    def generate(self, prompt: str, **kwargs: Any) -> str:
        """Generate a grounded completion from the local Ollama LLM.

        Args:
            prompt: The grounded QA prompt including context and question.
            **kwargs: Extra model generation options (e.g. temperature).

        Returns:
            The text response generated by Ollama.

        Raises:
            ValueError: If prompt is empty or whitespace-only.
            GenerationError: If Ollama is unreachable, returns an error,
                or is malformed.
        """
        if not prompt or not prompt.strip():
            raise ValueError("Prompt cannot be empty or whitespace-only.")

        url = f"{self.base_url}/api/generate"
        options = {"temperature": 0.0}
        options.update(kwargs)

        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": options,
        }

        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as response:
                raw_body = response.read().decode("utf-8")
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                raise GenerationError(
                    f"Ollama model '{self.model}' was not found. "
                    f"Run `ollama pull {self.model}` to download it."
                ) from exc
            raise GenerationError(
                f"Ollama HTTP error ({exc.code}): {exc.reason}"
            ) from exc
        except urllib.error.URLError as exc:
            raise GenerationError(
                f"Could not connect to Ollama at {self.base_url}: {exc.reason}. "
                "Ensure Ollama is running (`ollama serve`)."
            ) from exc
        except TimeoutError as exc:
            raise GenerationError(
                f"Ollama request timed out after {self.timeout}s."
            ) from exc
        except OSError as exc:
            raise GenerationError(
                f"I/O error communicating with Ollama at {self.base_url}: {exc}"
            ) from exc

        try:
            data = json.loads(raw_body)
        except json.JSONDecodeError as exc:
            raise GenerationError(
                f"Malformed JSON received from Ollama at {url}: {exc}"
            ) from exc

        if not isinstance(data, dict):
            raise GenerationError(
                "Malformed response from Ollama: expected a JSON object."
            )

        answer = data.get("response")
        if not isinstance(answer, str):
            raise GenerationError(
                "Malformed response from Ollama: missing 'response' text field."
            )

        return answer.strip()

    def generate_stream(self, prompt: str) -> Iterator[str]:
        """Stream tokens live from local Ollama ``/api/generate`` via stdlib NDJSON.

        Uses ``"stream": True`` and reads newline-delimited JSON objects one
        line at a time without any external HTTP library dependencies.

        Args:
            prompt: Formatted grounded QA prompt.

        Yields:
            Individual token strings as they arrive from Ollama.

        Raises:
            ValueError: If ``prompt`` is empty or whitespace-only.
            GenerationError: If the Ollama service is unreachable, returns an
                HTTP error, times out, or returns malformed JSON.
        """
        if not prompt or not prompt.strip():
            raise ValueError("Prompt must not be empty.")

        url = f"{self.base_url.rstrip('/')}/api/generate"
        payload = json.dumps(
            {
                "model": self.model,
                "prompt": prompt,
                "stream": True,
                "options": {"temperature": 0.0},
            }
        ).encode("utf-8")

        request = urllib.request.Request(
            url,
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                for raw_line in response:
                    line = raw_line.decode("utf-8").strip()
                    if not line:
                        continue
                    chunk = json.loads(line)
                    token = chunk.get("response", "")
                    if token:
                        yield str(token)
                    if chunk.get("done", False):
                        break
        except urllib.error.HTTPError as exc:
            raise GenerationError(
                f"Ollama streaming HTTP error ({exc.code}): {exc.reason}"
            ) from exc
        except urllib.error.URLError as exc:
            raise GenerationError(
                f"Could not connect to Ollama at {self.base_url} for streaming: "
                f"{exc.reason}. Ensure Ollama is running (`ollama serve`)."
            ) from exc
        except TimeoutError as exc:
            raise GenerationError(
                f"Ollama streaming request timed out after {self.timeout}s."
            ) from exc
        except json.JSONDecodeError as exc:
            raise GenerationError(
                f"Malformed JSON in Ollama streaming response: {exc}"
            ) from exc
        except OSError as exc:
            raise GenerationError(
                f"I/O error during Ollama streaming at {self.base_url}: {exc}"
            ) from exc
